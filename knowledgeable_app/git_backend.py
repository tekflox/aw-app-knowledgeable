"""docs/design/aw-knowledgeable-fs-sync.md §16.2-§16.10 — the git backend.

``knowledge_base/`` itself is the git worktree (``.git/`` lives inside the
tree this app's bulk-ingest scanner already walks — which is exactly why
§16.1's leading-dot rule, already shipped in :mod:`bulk_ingest`, had to land
first). Each tick, after the graph upsync, this module stages the whole
tree minus the generated code-map subtrees (``skip_prefixes``, via a
generated ``.gitignore``), commits if anything changed, and pushes —
fast-forward-only, never force. One remote repo per workspace install.

**Direction is push-only** (§16.4) — the tree is the corpus's primary home,
git is a mirror, never a second writer. A non-fast-forward push rejection
(a human edited the mirror on GitHub, another writer pushed, the remote was
handed to this connector non-empty) is classified as ``diverged`` and
stopped, never merged/rebased/force-pushed — see :func:`_classify_push_failure`.

**Credentials** (§16.3): ``ctx.secrets`` key ``git_token``, injected
per-invocation as an environment-only ``http.<url>.extraheader`` — never in
argv, never in the remote URL, never written to ``.git/config``, never on
disk. Callers never pass ``GIT_TRACE``/``GIT_CURL_VERBOSE`` through this
module's :func:`_run` (§16.10 risk 3 — both print the Authorization header).

This module takes plain values (``root``/``remote_url``/``branch``/
``token``/``workspace_slug``/``bucket``/``skip_prefixes``), never a ``ctx``
and never an import of :mod:`bulk_ingest` — ``routes.py``/``bulk_ingest.py``
read the KB-tree specifics (``kb_root()``, ``SKIP_PREFIXES``, ``BUCKET``)
and thread them in, the same seam ``bulk_ingest.py`` already documents for
``ctx.db``/``ctx.state.lease``. A one-way dependency, not circular: this
keeps the git engine a pure, independently testable piece, and is also what
``bulk_ingest`` importing this module requires (the reverse import would be
circular).
"""
from __future__ import annotations

import base64
import json
import logging
import os
import subprocess
import time
from pathlib import Path
from urllib.parse import urlsplit

log = logging.getLogger("aw_apps.knowledgeable.git_backend")

GIT_TOKEN_SECRET = "git_token"
MARKER_FILENAME = ".aw-kb-sync.json"
GITIGNORE_FILENAME = ".gitignore"
GITIGNORE_HEADER = "# generated by aw-app-knowledgeable — kept equal to bulk_ingest.SKIP_PREFIXES\n"

#: §16.10 risk 2 — a hung subprocess must not wedge the lease forever; the
#: lease releases on process exit, not on tick timeout.
GIT_TIMEOUT_S = 30

STATE_OK = "ok"
STATE_NO_SECRET = "no_secret"
STATE_AUTH_FAILED = "auth_failed"
STATE_DIVERGED = "diverged"
STATE_PUSH_FAILED = "push_failed"


class GitBackendError(Exception):
    """Carries a declared ``git_state`` + human reason. Never let one of
    these escape :func:`sync_tick` uncaught — §16.10 risk 6: a step that
    catches its own failure and returns success silently disables the
    whole visibility story."""

    def __init__(self, state: str, detail: str) -> None:
        super().__init__(detail)
        self.state = state
        self.detail = detail


def gitignore_body(skip_prefixes: tuple[str, ...]) -> str:
    """The generated ``.gitignore`` — one line per entry in
    ``skip_prefixes`` (the caller's ``bulk_ingest.SKIP_PREFIXES``, always —
    there is no second, hand-copied list here to drift from, §16.10 risk 4),
    anchored at the repo root so the whole subtree is ignored rather than
    re-matched per file."""
    lines = [GITIGNORE_HEADER]
    for prefix in skip_prefixes:
        lines.append(f"/{prefix}")
    return "\n".join(lines) + "\n"


def _validate_remote_url(remote_url: str) -> None:
    parsed = urlsplit(remote_url)
    if parsed.username or parsed.password:
        raise GitBackendError(
            STATE_AUTH_FAILED,
            "git_remote_url carries userinfo (https://user:token@...) — a credential "
            "in plain config is rejected; use git_token instead",
        )


def _run(
    args: list[str],
    cwd: Path,
    token: str | None = None,
    remote_url: str | None = None,
    env_extra: dict[str, str] | None = None,
) -> subprocess.CompletedProcess:
    """Every git invocation in this module goes through here — one place
    that always sets ``GIT_TERMINAL_PROMPT=0`` (auth failure must never
    block on a prompt) and the per-invocation credential env (never argv,
    never the URL, never written to disk — §16.3)."""
    env = {
        "GIT_TERMINAL_PROMPT": "0",
        "HOME": os.environ.get("HOME", "/tmp"),
        "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
    }
    if token and remote_url:
        parsed = urlsplit(remote_url)
        if parsed.scheme in ("http", "https"):
            match_url = f"{parsed.scheme}://{parsed.netloc}/"
            basic = base64.b64encode(f"x-access-token:{token}".encode()).decode()
            env["GIT_CONFIG_COUNT"] = "1"
            env["GIT_CONFIG_KEY_0"] = f"http.{match_url}.extraheader"
            env["GIT_CONFIG_VALUE_0"] = f"Authorization: Basic {basic}"
    if env_extra:
        env.update(env_extra)
    try:
        return subprocess.run(
            ["git", *args],
            cwd=str(cwd),
            env=env,
            capture_output=True,
            text=True,
            timeout=GIT_TIMEOUT_S,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise GitBackendError(
            STATE_PUSH_FAILED, f"git {args[0]} timed out after {GIT_TIMEOUT_S}s"
        ) from exc


def _classify_push_failure(stderr: str) -> str:
    """A plain ``git push`` already fails on non-fast-forward (§16.4) —
    this classifies that failure rather than fighting it. Never merge,
    rebase, or force-push on any of these."""
    low = stderr.lower()
    if (
        "authentication failed" in low
        or "invalid username or token" in low
        or "403" in low
        or " 401" in low
        or "permission denied" in low
    ):
        return STATE_AUTH_FAILED
    if "rejected" in low and (
        "fetch first" in low or "non-fast-forward" in low or "not have locally" in low
    ):
        return STATE_DIVERGED
    return STATE_PUSH_FAILED


def _ensure_git_init(root: Path, branch: str) -> None:
    if not (root / ".git").is_dir():
        result = _run(["init", "-q"], cwd=root)
        if result.returncode != 0:
            raise GitBackendError(STATE_PUSH_FAILED, f"git init failed: {result.stderr.strip()}")
    # Safe on a brand-new repo (no commits — just moves the symref) and on
    # an existing one (resets the local branch pointer to current HEAD).
    result = _run(["checkout", "-B", branch], cwd=root)
    if result.returncode != 0:
        raise GitBackendError(
            STATE_PUSH_FAILED, f"git checkout -B {branch} failed: {result.stderr.strip()}"
        )


def _ensure_remote(root: Path, remote_url: str) -> None:
    existing = _run(["remote", "get-url", "origin"], cwd=root)
    if existing.returncode != 0:
        result = _run(["remote", "add", "origin", remote_url], cwd=root)
    elif existing.stdout.strip() != remote_url:
        result = _run(["remote", "set-url", "origin", remote_url], cwd=root)
    else:
        return
    if result.returncode != 0:
        raise GitBackendError(STATE_PUSH_FAILED, f"git remote setup failed: {result.stderr.strip()}")


def _write_gitignore_if_changed(root: Path, skip_prefixes: tuple[str, ...]) -> None:
    path = root / GITIGNORE_FILENAME
    body = gitignore_body(skip_prefixes)
    if not path.is_file() or path.read_text(encoding="utf-8") != body:
        path.write_text(body, encoding="utf-8")


def _read_marker(root: Path) -> dict | None:
    path = root / MARKER_FILENAME
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def _write_marker(root: Path, workspace_slug: str, bucket: str) -> None:
    marker = {
        "workspace_slug": workspace_slug,
        "bucket": bucket,
        "initialized_at": time.time(),
    }
    (root / MARKER_FILENAME).write_text(json.dumps(marker, indent=2) + "\n", encoding="utf-8")


def _stage_all(root: Path) -> tuple[int, int, int, list[str]]:
    """``git add -A`` (honors ``.gitignore``), then classify what got
    staged from ``git diff --cached --name-status`` — the commit message's
    ``+created ~updated -deleted`` counts (§16.6)."""
    add_result = _run(["add", "-A"], cwd=root)
    if add_result.returncode != 0:
        raise GitBackendError(STATE_PUSH_FAILED, f"git add -A failed: {add_result.stderr.strip()}")
    diff_result = _run(["diff", "--cached", "--name-status"], cwd=root)
    if diff_result.returncode != 0:
        raise GitBackendError(
            STATE_PUSH_FAILED, f"git diff --cached failed: {diff_result.stderr.strip()}"
        )
    created = updated = deleted = 0
    paths: list[str] = []
    for line in diff_result.stdout.splitlines():
        if not line.strip():
            continue
        code, _, rest = line.partition("\t")
        path = rest.split("\t")[-1]
        paths.append(path)
        if code.startswith("A"):
            created += 1
        elif code.startswith("D"):
            deleted += 1
        else:  # M, R*, C*, T
            updated += 1
    return created, updated, deleted, paths


def _commit(root: Path, workspace_slug: str, created: int, updated: int, deleted: int, paths: list[str]) -> None:
    tick_iso = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    subject = f"kb-sync: +{created} ~{updated} -{deleted} [{workspace_slug} {tick_iso}]"
    shown = paths[:50]
    body_lines = shown
    if len(paths) > len(shown):
        body_lines = shown + [f"... and {len(paths) - len(shown)} more"]
    message = subject + ("\n\n" + "\n".join(body_lines) if body_lines else "")
    author_name = f"aw-kb-sync ({workspace_slug})"
    author_email = f"kb-sync@{workspace_slug}.invalid"
    env_extra = {
        "GIT_AUTHOR_NAME": author_name,
        "GIT_AUTHOR_EMAIL": author_email,
        "GIT_COMMITTER_NAME": author_name,
        "GIT_COMMITTER_EMAIL": author_email,
    }
    result = _run(["commit", "-q", "-m", message], cwd=root, env_extra=env_extra)
    if result.returncode != 0:
        raise GitBackendError(STATE_PUSH_FAILED, f"git commit failed: {result.stderr.strip()}")


def _push(root: Path, remote_url: str, branch: str, token: str) -> dict:
    result = _run(["push", "origin", f"{branch}:{branch}"], cwd=root, token=token, remote_url=remote_url)
    if result.returncode == 0:
        return {"state": STATE_OK, "detail": "pushed"}
    state = _classify_push_failure(result.stderr)
    return {"state": state, "detail": result.stderr.strip()[:2000]}


def sync_tick(
    root: Path,
    remote_url: str,
    branch: str,
    token: str,
    workspace_slug: str,
    bucket: str,
    skip_prefixes: tuple[str, ...],
) -> dict | None:
    """The one entrypoint — called from inside the bulk-ingest tick's lease
    hold (§16.7), after the graph upsync (§16.10 risk 8). Returns ``None``
    when the feature is not configured (no ``git_remote_url`` set — nothing
    to do, no ``git_state`` recorded at all). Otherwise always returns a
    dict with ``state`` in :data:`STATE_OK`/``no_secret``/``auth_failed``/
    ``diverged``/``push_failed`` plus a human ``detail`` — never raises:
    every :class:`GitBackendError` is caught here and turned into the
    declared state (§16.10 risk 6).
    """
    if not remote_url:
        return None
    try:
        _validate_remote_url(remote_url)
        if not workspace_slug:
            raise GitBackendError(
                STATE_PUSH_FAILED,
                "AW_WORKSPACE is empty — refusing (workspace_slug is part of the "
                "marker's identity, same correctness-boundary rule as fs_sync §6)",
            )

        root.mkdir(parents=True, exist_ok=True)

        _ensure_git_init(root, branch)
        _ensure_remote(root, remote_url)

        # §16.5 risk 1 — checked before this tick touches anything else in
        # the tree: a mismatched marker means another workspace's install
        # already owns this local `knowledge_base/` (a copy-pasted config,
        # a cloned workspace). Refuse outright rather than commit on top of it.
        marker = _read_marker(root)
        if marker is not None and marker.get("workspace_slug") != workspace_slug:
            return {
                "state": STATE_DIVERGED,
                "detail": (
                    f"{MARKER_FILENAME} is claimed by workspace "
                    f"{marker.get('workspace_slug')!r}, not {workspace_slug!r} — refusing"
                ),
                "committed": False,
            }
        if marker is None:
            _write_marker(root, workspace_slug, bucket)

        _write_gitignore_if_changed(root, skip_prefixes)
        created, updated, deleted, paths = _stage_all(root)
        committed = bool(created or updated or deleted)
        if committed:
            _commit(root, workspace_slug, created, updated, deleted, paths)

        if not token:
            return {
                "state": STATE_NO_SECRET,
                "detail": "git_token not set — commit kept local, not pushed",
                "committed": committed,
            }

        result = _push(root, remote_url, branch, token)
        result["committed"] = committed
        return result
    except GitBackendError as exc:
        log.warning("git backend: %s: %s", exc.state, exc.detail)
        return {"state": exc.state, "detail": exc.detail, "committed": False}
